//! The twelve language tables.
//!
//! Each table is a `&'static [&str]` of exactly [`Text::COUNT`] entries, in the
//! order the enum declares. Two things follow from that shape:
//!
//! * adding a string is a compile error until every language supplies it, so
//!   a half-translated release cannot ship by accident;
//! * a lookup is an index, so choosing a language costs nothing at runtime.
//!
//! The two plural nouns live in their own small table
//! ([`crate::services::i18n::PluralText`]), indexed by plural form, because
//! only a couple of strings vary with a count.
//!
//! A note on dates: no table uses chrono's `%A` or `%B`. Those come from
//! chrono's own English-only tables, which is why the weekday and month names
//! are catalogue keys and [`crate::services::i18n::Catalog::date_full`]
//! assembles them — in whatever word order the language wants, since that
//! differs more between these twelve than the names themselves do.
//!
//! This file is generated from a table in one piece per language; the entries
//! are positional, so a translation has to keep its place. Adding a language
//! means adding one block below and one entry to [`Language::ALL`].

