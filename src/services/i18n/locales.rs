    #[test]
    fn no_translation_was_left_in_english_by_accident() {
        // A guard on the generated tables: a string that still reads exactly
        // like the English one is either a genuine loan ("Alarm" in German) or
        // a copy-and-paste that was never translated. The list below is the
        // reviewed set of loans, so anything new has to be looked at.
        const REVIEWED_LOANS: &[(Language, Text)] = &[
            (Language::German, Text::ActionDismiss), // "Ausblenden" — translated
        ];
        for language in Language::ALL {
            if language == Language::English {
                continue;
            }
            for key in [Text::PageClock, Text::ActionSave, Text::ActionCancel] {
                let mine = Catalog::new(language).text(key);
                let english = Catalog::english().text(key);
                if mine == english {
                    assert!(
                        REVIEWED_LOANS.contains(&(language, key)),
                        "{language:?} left {key:?} as the English {english:?}"
                    );
                }
            }
        }
    }
